import { OrganizerEventReportDto } from '../dto/organizer-event-report.dto';
import { OrganizerEventReportModel } from '../models/organizer-event-report.model';

export function organizerEventReportDtoToModel(
  dto: OrganizerEventReportDto,
): OrganizerEventReportModel {
  return {
    event: {
      id: dto.event.id,
      publicUuid: dto.event.publicUuid,
      slug: dto.event.slug,
      name: dto.event.name,
      category: dto.event.category,
      status: dto.event.status,
      statusLabel: dto.event.statusLabel,
      eventCode: dto.event.eventCode,
      venue: dto.event.venue,
      address: dto.event.address,
      city: dto.event.city,
      imageUrl: dto.event.imageUrl,
      hasLandingPage: Boolean(dto.event.hasLandingPage),
      feeChargedTo: dto.event.feeChargedTo || 'buyer',
      createdAt: dto.event.createdAt,
      settlementStatus: dto.event.settlementStatus || null,
      settlementStatusLabel: dto.event.settlementStatusLabel || null,
      settlementAmount: dto.event.settlementAmount ? Number(dto.event.settlementAmount) : null,
      settlementBankName: dto.event.settlementBankName || null,
      settlementRequestedAt: dto.event.settlementRequestedAt || null,
    },
    summary: {
      totalCapacity: Number(dto.summary.totalCapacity) || 0,
      ticketsSold: Number(dto.summary.ticketsSold) || 0,
      ticketsUsed: Number(dto.summary.ticketsUsed) || 0,
      ticketsRemaining: Number(dto.summary.ticketsRemaining) || 0,
      occupancyPercentage: Number(dto.summary.occupancyPercentage) || 0,
      checkInPercentage: Number(dto.summary.checkInPercentage) || 0,
      grossRevenue: Number(dto.summary.grossRevenue) || 0,
      totalServiceFee: Number(dto.summary.totalServiceFee) || 0,
      couponsDiscountAmount: Number(dto.summary.couponsDiscountAmount) || 0,
      netSalesRevenue: Number(dto.summary.netSalesRevenue) || 0,
      averageTicketPrice: Number(dto.summary.averageTicketPrice) || 0,
      targetRevenue: Number(dto.summary.targetRevenue) || 0,
      targetRevenuePercentage: Number(dto.summary.targetRevenuePercentage) || 0,
      totalOrdersCount: Number(dto.summary.totalOrdersCount) || 0,
    },
    zones: (dto.zones || []).map((z) => ({
      id: z.id,
      publicUuid: z.publicUuid,
      name: z.name,
      color: z.color,
      capacity: Number(z.capacity) || 0,
      soldCount: Number(z.soldCount) || 0,
      usedCount: Number(z.usedCount) || 0,
      remainingTickets: Number(z.remainingTickets) || 0,
      occupancyPercentage: Number(z.occupancyPercentage) || 0,
      regularPrice: Number(z.regularPrice) || 0,
      activePrice: Number(z.activePrice) || 0,
      activeTierName: z.activeTierName,
      isPresaleActive: Boolean(z.isPresaleActive),
      revenue: Number(z.revenue) || 0,
      feeIncluded: Boolean(z.feeIncluded),
      serviceFee: Number(z.serviceFee) || 0,
      tiers: (z.tiers || []).map((t) => ({
        tierNumber: t.tierNumber,
        name: t.name,
        price: Number(t.price) || 0,
        capacity: Number(t.capacity) || 0,
        soldCount: Number(t.soldCount) || 0,
        endAt: t.endAt,
        isActive: Boolean(t.isActive),
        statusBadge: t.statusBadge,
      })),
    })),
    shows: (dto.shows || []).map((s) => ({
      id: s.id,
      publicUuid: s.publicUuid,
      name: s.name,
      startTime: s.startTime,
      dateFormatted: s.dateFormatted,
      salesEndAt: s.salesEndAt,
      durationHours: Number(s.durationHours) || 2,
      status: s.status,
      ticketsSold: Number(s.ticketsSold) || 0,
      ticketsUsed: Number(s.ticketsUsed) || 0,
    })),
    recentOrders: (dto.recentOrders || []).map((o) => ({
      id: o.id,
      publicUuid: o.publicUuid,
      orderCode: o.orderCode,
      createdAt: o.createdAt,
      buyerName: o.buyerName,
      buyerEmail: o.buyerEmail,
      ticketsCount: Number(o.ticketsCount) || 0,
      zonesSummary: o.zonesSummary,
      subtotal: Number(o.subtotal) || 0,
      discountAmount: Number(o.discountAmount) || 0,
      couponCode: o.couponCode,
      totalAmount: Number(o.totalAmount) || 0,
      paymentMethod: o.paymentMethod,
      status: o.status,
    })),
    dailySales: (dto.dailySales || []).map((d) => ({
      date: d.date,
      ticketsSold: Number(d.ticketsSold) || 0,
      revenue: Number(d.revenue) || 0,
      zones: (d.zones || []).map((z) => ({
        zoneId: z.zoneId,
        zoneName: z.zoneName,
        color: z.color || '#6366F1',
        ticketsSold: Number(z.ticketsSold) || 0,
        revenue: Number(z.revenue) || 0,
      })),
    })),
    funnel: dto.funnel
      ? {
          pageviews: Number(dto.funnel.pageviews) || 0,
          uniqueVisitors: Number(dto.funnel.uniqueVisitors) || 0,
          checkoutInitiated: Number(dto.funnel.checkoutInitiated) || 0,
          ordersPaid: Number(dto.funnel.ordersPaid) || 0,
          conversionRate: Number(dto.funnel.conversionRate) || 0,
          steps: (dto.funnel.steps || []).map((s) => ({
            step: s.step,
            count: Number(s.count) || 0,
            percentage: Number(s.percentage) || 0,
            dropOffPercentage: Number(s.dropOffPercentage) || 0,
          })),
          trafficSources: (dto.funnel.trafficSources || []).map((ts) => ({
            source: ts.source,
            visitors: Number(ts.visitors) || 0,
            percentage: Number(ts.percentage) || 0,
          })),
        }
      : null,
  };
}
